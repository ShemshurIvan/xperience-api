create table users (
    id         bigint generated by default as identity primary key,
    first_name varchar(255) not null,
    last_name  varchar(255) not null,
    age        integer      not null,
    email      varchar(255) not null,
    password   varchar(255) not null,
    role       varchar(20)  not null,
    constraint uk_users_email unique (email),
    constraint ck_users_role check (role in ('USER', 'SELLER', 'ADMIN'))
);

create table products (
    id               bigint generated by default as identity primary key,
    owner_id         bigint        not null,
    name             varchar(100)  not null,
    description      varchar(2000),
    price            numeric(38, 2) not null,
    max_people       integer       not null,
    duration_minutes integer       not null,
    created_at       timestamp(6)  not null,
    constraint fk_products_owner foreign key (owner_id) references users (id),
    constraint ck_products_price check (price >= 0),
    constraint ck_products_max_people check (max_people >= 1),
    constraint ck_products_duration check (duration_minutes >= 1)
);

create table time_slots (
    id                 bigint generated by default as identity primary key,
    product_id         bigint       not null,
    start_time         timestamp(6) not null,
    end_time           timestamp(6) not null,
    max_people_in_slot integer      not null,
    booked_people      integer      not null,
    status             varchar(20)  not null,
    version            bigint       not null,
    constraint fk_time_slots_product foreign key (product_id) references products (id),
    constraint uk_time_slot_product_start unique (product_id, start_time),
    constraint ck_time_slots_max_people check (max_people_in_slot >= 1),
    constraint ck_time_slots_booked_people check (booked_people >= 0),
    constraint ck_time_slots_status check (status in ('OPEN', 'FULL', 'CANCELLED'))
);

create table reservations (
    id            bigint generated by default as identity primary key,
    time_slot_id  bigint         not null,
    guest_id      bigint,  -- empty once the guest has deleted their account; the booking is kept
    number_people integer        not null,
    price_paid    numeric(38, 2) not null,
    status        varchar(20)    not null,
    constraint fk_reservations_time_slot foreign key (time_slot_id) references time_slots (id),
    constraint fk_reservations_guest foreign key (guest_id) references users (id),
    constraint ck_reservations_number_people check (number_people >= 1),
    constraint ck_reservations_status check (status in ('PENDING', 'CONFIRMED', 'CANCELLED'))
);

create table cart_items (
    id            bigint generated by default as identity primary key,
    user_id       bigint       not null,
    time_slot_id  bigint       not null,
    number_people integer      not null,
    added_at      timestamp(6) not null,
    constraint fk_cart_items_user foreign key (user_id) references users (id),
    constraint fk_cart_items_time_slot foreign key (time_slot_id) references time_slots (id),
    constraint uk_cart_item_user_slot unique (user_id, time_slot_id),
    constraint ck_cart_items_number_people check (number_people >= 1)
);


create index idx_products_owner on products (owner_id);
create index idx_reservations_time_slot on reservations (time_slot_id);
create index idx_reservations_guest on reservations (guest_id);
create index idx_cart_items_time_slot on cart_items (time_slot_id);